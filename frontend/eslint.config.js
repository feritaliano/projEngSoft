// @ts-check
const eslint = require('@eslint/js');
const { defineConfig } = require('eslint/config');
const tseslint = require('typescript-eslint');
const angular = require('angular-eslint');

// Value fields of the API contract (backend/openapi/openapi.json): decimal strings such as value (the decimal of every
// DerivedValue: averagePrice, totalCost, realizedProfit...), quantity, unitPrice, fees, availableQuantity, step; the
// suffixes cover names to come (marketValue, yieldPercent...). Only these names are checked. Counts such as total
// (pagination) or operationCount are numbers and stay allowed; a local number named like a value field (a wizard step)
// must be renamed.
const ARITHMETIC = ['+', '-', '*', '/', '%', '**'];
const VALUE_FIELD =
  'MemberExpression[property.name=/^(value|quantity|step|fees|price|cost|amount|profit|percent)$|(Quantity|Price|Cost|Amount|Profit|Fees|Value|Percent)$/]';

module.exports = defineConfig([
  // Generated by ng-openapi-gen (npm run api:generate); never edited by hand.
  { ignores: ['src/app/api/**'] },
  {
    files: ['**/*.ts'],
    extends: [
      eslint.configs.recommended,
      tseslint.configs.recommended,
      tseslint.configs.stylistic,
      angular.configs.tsRecommended,
    ],
    processor: angular.processInlineTemplates,
    rules: {
      '@angular-eslint/directive-selector': [
        'error',
        {
          type: 'attribute',
          prefix: 'app',
          style: 'camelCase',
        },
      ],
      '@angular-eslint/component-selector': [
        'error',
        {
          type: 'element',
          prefix: 'app',
          style: 'kebab-case',
        },
      ],
    },
  },
  {
    // D5, D28, RN11: money, quantities and percentages arrive as decimal strings and are never turned into number
    // nor used in arithmetic here; the backend computes, the frontend formats. Checked by scripts/check-money-lint.mjs.
    // "R$ " + p.value is also refused (use a pipe or a template literal). Templates are not linted: strictTemplates
    // (tsconfig.json) refuses arithmetic on a string there.
    files: ['src/app/**/*.ts'],
    ignores: [
      // Only exception: chart data, which the plotting library needs as number. Keep it in *.chart.ts files.
      'src/app/**/*.chart.ts',
    ],
    rules: {
      'no-restricted-syntax': [
        'error',
        ...[
          // Also Number.parseFloat, globalThis.Number, window.parseInt...
          ':matches(CallExpression, NewExpression)[callee.name=/^(Number|parseFloat|parseInt)$/]',
          ':matches(CallExpression, NewExpression)[callee.property.name=/^(Number|parseFloat|parseInt)$/]',
          "UnaryExpression[operator='+']",
        ].map((selector) => ({
          selector,
          message:
            'No number conversion in src/app (D5, D28, RN11): format the decimal string from the API.',
        })),
        ...[
          `BinaryExpression:matches(${ARITHMETIC.map((op) => `[operator='${op}']`).join(', ')})`,
          `AssignmentExpression:matches(${ARITHMETIC.map((op) => `[operator='${op}=']`).join(', ')})`,
          "UnaryExpression[operator='-']",
          'UpdateExpression',
        ]
          .flatMap((parent) => [
            `${parent} > ${VALUE_FIELD}`,
            // p?.value, p.value!, p.value as unknown as number...
            `${parent} > :matches(ChainExpression, TSAsExpression, TSNonNullExpression, TSSatisfiesExpression) ${VALUE_FIELD}`,
          ])
          .map((selector) => ({
            selector,
            message:
              'No arithmetic on API value fields (D5, D28, RN11): the backend computes every derived value.',
          })),
      ],
    },
  },
  {
    files: ['**/*.html'],
    extends: [angular.configs.templateRecommended, angular.configs.templateAccessibility],
    rules: {},
  },
]);
