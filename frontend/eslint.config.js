// @ts-check
const eslint = require('@eslint/js');
const { defineConfig } = require('eslint/config');
const tseslint = require('typescript-eslint');
const angular = require('angular-eslint');

// Value fields of the API contract (backend/openapi/openapi.json): decimal strings such as value, quantity, unitPrice,
// fees, availableQuantity, step, and the money names to come (averagePrice, totalCost, realizedProfit, marketValue...).
// Counts such as total (pagination) or operationCount are numbers and stay allowed.
const ARITHMETIC = ['+', '-', '*', '/', '%', '**'];
const VALUE_FIELD =
  'MemberExpression[property.name=/^(value|quantity|step|fees|price|cost|amount|profit)$|(Quantity|Price|Cost|Amount|Profit|Fees|Value)$/]';

module.exports = defineConfig([
  // Generated by ng-openapi-gen (npm run api:generate); never edited by hand.
  { ignores: ['src/app/api/**'] },
  {
    files: ['**/*.ts'],
    extends: [
      eslint.configs.recommended,
      tseslint.configs.recommended,
      tseslint.configs.stylistic,
      angular.configs.tsRecommended,
    ],
    processor: angular.processInlineTemplates,
    rules: {
      '@angular-eslint/directive-selector': [
        'error',
        {
          type: 'attribute',
          prefix: 'app',
          style: 'camelCase',
        },
      ],
      '@angular-eslint/component-selector': [
        'error',
        {
          type: 'element',
          prefix: 'app',
          style: 'kebab-case',
        },
      ],
    },
  },
  {
    // D5, D28, RN11: money, quantities and percentages arrive as decimal strings and are never turned into number
    // nor used in arithmetic here; the backend computes, the frontend formats. Checked by scripts/check-money-lint.mjs.
    files: ['src/app/**/*.ts'],
    ignores: [
      // Only exception: chart data, which the plotting library needs as number. Keep it in *.chart.ts files.
      'src/app/**/*.chart.ts',
    ],
    rules: {
      'no-restricted-syntax': [
        'error',
        ...[
          'CallExpression[callee.name=/^(Number|parseFloat|parseInt)$/]',
          "NewExpression[callee.name='Number']",
          "CallExpression[callee.object.name='Number'][callee.property.name=/^parse(Float|Int)$/]",
          "UnaryExpression[operator='+']",
        ].map((selector) => ({
          selector,
          message:
            'No number conversion in src/app (D5, D28, RN11): format the decimal string from the API.',
        })),
        ...[
          `BinaryExpression:matches(${ARITHMETIC.map((op) => `[operator='${op}']`).join(', ')})`,
          `AssignmentExpression:matches(${ARITHMETIC.map((op) => `[operator='${op}=']`).join(', ')})`,
          "UnaryExpression[operator='-']",
          'UpdateExpression',
        ]
          .flatMap((parent) => [
            `${parent} > ${VALUE_FIELD}`,
            `${parent} > ChainExpression > ${VALUE_FIELD}`,
          ])
          .map((selector) => ({
            selector,
            message:
              'No arithmetic on API value fields (D5, D28, RN11): the backend computes every derived value.',
          })),
      ],
    },
  },
  {
    files: ['**/*.html'],
    extends: [angular.configs.templateRecommended, angular.configs.templateAccessibility],
    rules: {},
  },
]);
